def score_files(paths: List[str]) -> None:
    metrics = official_metric_fns()
    for p in paths:
        store = ResumableJSONL(p, config=None, strict_config=False, read_only=True)
        latest = store.load_latest()
        store.close()
        recs = [r for r in latest.values() if not r.get("error")]
        n_err = len(latest) - len(recs)
        if not recs:
            continue
        meta = {}
        if os.path.exists(p + ".meta.json"):
            with open(p + ".meta.json", encoding="utf-8") as f:
                meta = json.load(f)
        print(f"\n=== {os.path.basename(p)} ===")
        print(f"{meta.get('model','?')} arm={meta.get('arm','?')} "
              f"preset={meta.get('preset','-')} quant={meta.get('quant','-')}")
        if n_err:
            print(f"[warn] {n_err} item(s) still failing; excluded. Rerun to retry.")

        # task -> length -> scores
        grid: Dict[str, Dict[int, List[float]]] = defaultdict(lambda: defaultdict(list))
        for r in recs:
            fam = TASK_FAMILY.get(r.get("task"))
            if fam is None:
                continue
            fn = metrics[fam]
            # The official scorers take LISTS and return a percentage.
            grid[r["task"]][r["length"]].append(
                fn([r.get("text", "")], [r.get("outputs", [])]))

        lengths = sorted({L for t in grid for L in grid[t]})
        if not lengths:
            continue
        print(f"{'task':>18} " + " ".join(f"{L:>8}" for L in lengths))
        col_all: Dict[int, List[float]] = defaultdict(list)
        for task in RULER_13:
            if task not in grid:
                continue
            cells = []
            for L in lengths:
                v = grid[task].get(L)
                if v:
                    cells.append(f"{sum(v)/len(v):>8.1f}")
                    col_all[L] += v
                else:
                    cells.append(f"{'-':>8}")
            print(f"{task:>18} " + " ".join(cells))
        print(f"{'RULER avg':>18} " + " ".join(
            f"{(sum(col_all[L])/len(col_all[L])):>8.1f}" if col_all.get(L) else f"{'-':>8}"
            for L in lengths))

        sysm = defaultdict(list)
        for r in recs:
            for k in ("ttft_s", "decode_tps", "peak_decode_gb", "kv_physical_gb",
                      "kv_compression_x"):
                if isinstance(r.get(k), (int, float)):
                    sysm[k].append(float(r[k]))
        if sysm:
            def avg(k):
                return sum(sysm[k]) / len(sysm[k]) if sysm.get(k) else float("nan")
            print(f"  ttft {avg('ttft_s'):.2f}s | decode {avg('decode_tps'):.1f} tok/s "
                  f"| peak {avg('peak_decode_gb'):.2f} GB "
                  f"| KV {avg('kv_physical_gb'):.3f} GB ({avg('kv_compression_x'):.1f}x)")


def build_ruler_prompt(tok, item, thinking: bool = False) -> str:
    """Wrap the bare task text in the model's chat template.

    RULER builds prompts as `model_template.format(task) + answer_prefix`. The
    data here was generated with template type `base` (no wrapper), so the
    wrapper is applied now, and the ANSWER PREFIX is re-attached AFTER the
    generation prompt -- it is the opening of the assistant's own turn, not
    part of the user's message.

    Without this, a reasoning model spends the task's whole generation budget
    inside a <think> block: measured 96% of dense outputs containing "<think>"
    and every NIAH task scoring 0.0.
    """
    sys.path.insert(0, HERE)
    from run_longbench_cuda import apply_template

    text = item["input"]
    prefix = item.get("answer_prefix") or ""
    if prefix and text.endswith(prefix):
        body = text[: -len(prefix)]
    else:
        body, prefix = text, ""

    try:
        wrapped = apply_template(tok, body, thinking)
    except Exception:                                            # noqa: BLE001
        return text                      # no chat template: use it raw
    return wrapped + prefix


def compare_files(paths):
    """Every arm on one grid, plus a PAIRED comparison against dense.

    RULER runs 20 samples per (task, length) here and its per-item scores are
    frequently 0 or 1, so a bare average invites reading noise as a result.
    Every arm answers the SAME generated items, so bootstrapping the per-item
    DIFFERENCE against dense removes item difficulty from the variance and is
    far tighter than two independent intervals at this n.
    """
    sys.path.insert(0, HERE)
    from run_longbench_cuda import _paired_bootstrap
    metrics = official_metric_fns()

    rows = {}
    by_item = {}
    meta_by_arm = {}

    for p in sorted(paths):
        store = ResumableJSONL(p, config=None, strict_config=False, read_only=True)
        latest = store.load_latest()
        store.close()
        recs = [r for r in latest.values() if not r.get("error")]
        if not recs:
            continue
        meta = {}
        if os.path.exists(p + ".meta.json"):
            with open(p + ".meta.json", encoding="utf-8") as f:
                meta = json.load(f)
        arm = meta.get("arm", "?")
        if meta.get("preset") and arm == "dkv":
            arm = "dkv/" + str(meta["preset"])
        meta_by_arm[arm] = meta
        by_item.setdefault(arm, {})
        per = defaultdict(list)
        for r in recs:
            fam = TASK_FAMILY.get(r.get("task"))
            if fam is None:
                continue
            v = metrics[fam]([r.get("text", "")], [r.get("outputs", [])])
            per[r["length"]].append(v)
            key = r.get("key") or (str(r["length"]) + "/" + r["task"] + "#" + str(r["idx"]))
            by_item[arm][key] = v
        rows[arm] = per

    if not rows:
        print("no scoreable RULER results")
        return

    lengths = sorted({L for per in rows.values() for L in per})
    m0 = next(iter(meta_by_arm.values()), {})
    print("")
    print("=== RULER — " + str(m0.get("model", "?")) + ", quant "
          + str(m0.get("quant", "?")) + " (13 tasks, avg over tasks x samples) ===")
    hdr = "{:>14} ".format("arm") + " ".join("{:>9}".format(L) for L in lengths)
    print(hdr)
    print("-" * len(hdr))
    for arm in sorted(rows, key=lambda a: (a != "dense", a)):
        cells = []
        for L in lengths:
            v = rows[arm].get(L)
            cells.append("{:>9.1f}".format(sum(v) / len(v)) if v else "{:>9}".format("-"))
        print("{:>14} ".format(arm) + " ".join(cells))

    if "dense" in by_item and len(by_item) > 1:
        print("")
        print("Paired against dense, on the items both arms answered "
              "(95% CI, 10k bootstrap resamples over items):")
        print("{:>14} {:>5} {:>11} {:>20}  verdict".format(
            "arm", "n", "mean delta", "95% CI"))
        for arm in sorted(a for a in by_item if a != "dense"):
            shared = sorted(set(by_item[arm]) & set(by_item["dense"]))
            if not shared:
                continue
            deltas = [by_item[arm][k] - by_item["dense"][k] for k in shared]
            mean = sum(deltas) / len(deltas)
            lo, hi = _paired_bootstrap(deltas)
            verdict = ("worse than dense" if hi < 0 else
                       "better than dense" if lo > 0 else
                       "NOT RESOLVED at this n")
            print("{:>14} {:>5} {:>11.2f} {:>20}  {}".format(
                arm, len(shared), mean, "[{:+.2f}, {:+.2f}]".format(lo, hi), verdict))


def main():
    # Before ANY torch.compile: without cl.exe on PATH the Inductor
    # decode path falls back to eager and every latency number here
    # understates DKV. Quality is unaffected; timings are not.
    from msvc_env import ensure_msvc
    global MSVC_OK
    MSVC_OK = ensure_msvc()
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", default="ibm-granite/granite-4.2-8b")
    ap.add_argument("--data", default="")
    ap.add_argument("--arm", default="dkv")
    ap.add_argument("--preset", default="mid", choices=["low", "mid", "high", "ultra"])
    ap.add_argument("--quant", default="nf4")
    ap.add_argument("--out", default="")
    ap.add_argument("--chunk", type=int, default=1024)
    ap.add_argument("--max-length", type=int, default=0,
                    help="skip generated lengths above this (the model's measured "
                         "non-spilling ceiling). 0 = run everything generated.")
    ap.add_argument("--tasks", nargs="+", default=RULER_13)
    ap.add_argument("--baseline-params", default="{}")
    ap.add_argument("--thinking", action="store_true",
                    help="let a reasoning model emit its <think> block. OFF by "
                         "default: RULER's per-task budgets (128 tokens for "
                         "NIAH, 30 for vt) cannot hold reasoning AND an answer.")
    ap.add_argument("--score", nargs="*", default=None)
    ap.add_argument("--compare", nargs="*", default=None,
                    help="one RULER table with every arm as a row, and exit")
    args = ap.parse_args()

    if args.compare is not None:
        paths = []
        for pat in (args.compare or ["paper/results/ruler/*.jsonl"]):
            paths.extend(sorted(glob.glob(pat)))
        if not paths:
            raise SystemExit("no result files matched")
        return compare_files(paths)

    if args.score is not None:
        paths: List[str] = []
        for pat in (args.score or ["paper/results/ruler/*.jsonl"]):
            paths.extend(sorted(glob.glob(pat)))
        if not paths:
            raise SystemExit("no result files matched")
        return score_files(paths)

    tag = args.model.split("/")[-1]
    data_dir = args.data or os.path.join(REPO, "paper", "results", "ruler_data", tag)
    if not os.path.isdir(data_dir):
        raise SystemExit(f"no generated RULER data at {data_dir}\n"
                         f"run benchmarks/generate_ruler_data.sh first")
    out = args.out or os.path.join(
        REPO, "paper", "results", "ruler",
        f"{tag}_{args.arm}{'_' + args.preset if args.arm == 'dkv' else ''}_{args.quant}.jsonl")

    cfg = {"model": args.model, "arm": args.arm, "quant": args.quant,
           "preset": args.preset if args.arm == "dkv" else None,
           "baseline_params": json.loads(args.baseline_params),
           "data_dir": os.path.abspath(data_dir),
           "decode_defaults": "serving" if args.arm == "dkv" else None,
           "prefill_attn": "sdpa",
           "thinking": bool(args.thinking),
           "prompt_template": "model-chat-template",
           # See run_longbench_cuda: a kernel change must invalidate DKV rows,
           # and the config alone cannot see one.
           "dkv_decode_rev": (decode_fingerprint() if args.arm == "dkv" else None),
           "protocol": "ruler-official-generators"}
    store = ResumableJSONL(out, config=cfg)
    done = store.load_done()

    items = [it for it in load_generated(data_dir)
             if it["task"] in args.tasks
             and (not args.max_length or it["length"] <= args.max_length)]
    work = [it for it in items if f"{it['length']}/{it['task']}#{it['idx']}" not in done]
    print(f"[ckpt] {out}\n[ckpt] {len(done)} recorded, {len(work)} pending "
          f"(of {len(items)} generated)")
    if not work:
        store.close()
        return score_files([out])

    gen_tokens = official_gen_tokens()
    sys.path.insert(0, ACTIVE)
    import torch
    import kv_baselines as KB
    from run_longbench_cuda import load_plain, derive_stop_ids, strip_prompt_echo, dkv_kv_bytes

    if args.arm == "dkv":
        os.environ.setdefault("DKV_RSVD_SEED", "1234")
        os.environ.setdefault("DKV_SVD_SEED", "1234")
        cwd = os.getcwd()
        os.chdir(ACTIVE)
        # BENCHMARK THE CONFIGURATION THAT SHIPS, NOT THE LIBRARY DEFAULTS.
        # serving/cli.py and the OpenAI gateway both call this before building
        # the wrapper; a harness that constructs DKVHFWrapper directly does not,
        # and the difference is not cosmetic. With DKV_SPARSE_BIAS unset it
        # takes the value "0.0", which selects the COMBINED decode branch --
        # a code path production never runs. dkv_attention.py's own comment on
        # that branch records what has lived there: "It only ever fired on the
        # combined branch -- DKV_SPARSE_BIAS unset or 0.0, the LIBRARY DEFAULT.
        # BEST_DECODE_DEFAULTS sets it to auto, which takes the production
        # branch, so everything going through the serving defaults was
        # unaffected and never saw it", measured at KL 11.76 with top-1 0/5
        # against KL 0.00125 and 5/5 once fixed.
        #
        # Every explicit env still wins (this is setdefault), so the arm knobs
        # set above are untouched.
        from serving.decode_config import apply_best_decode_defaults
        apply_best_decode_defaults()
        from serving.hf_dkv_wrapper import DKVHFWrapper
        w = DKVHFWrapper(model_id=args.model,
                         config={"preset": args.preset,
                                 "quantization": args.quant or None})
        w.ensure_loaded()
        tok, model = w.tokenizer, None
        os.chdir(cwd)
    else:
        tok, model = load_plain(args.model, args.quant, KB.needs_eager(args.arm))
        w = None
    stop_ids = derive_stop_ids(tok)
    bparams = json.loads(args.baseline_params)

    t_start = time.time()
    for n, it in enumerate(work, 1):
        key = f"{it['length']}/{it['task']}#{it['idx']}"
        prompt = build_ruler_prompt(tok, it, thinking=args.thinking)
        gl = gen_tokens[TASK_FAMILY[it["task"]]]
        try:
            if args.arm == "dkv":
                sid = f"ruler-{it['length']}-{it['task']}-{it['idx']}"
                try:
                    w.clear_session(sid)
                except Exception:                                # noqa: BLE001
                    pass
                w.active_session = sid
                torch.cuda.reset_peak_memory_stats()
                t0 = time.perf_counter()
                text = w.generate(prompt, max_new_tokens=gl, temperature=0.0,
                                  top_p=1.0, repetition_penalty=1.0)
                if isinstance(text, dict):
                    text = text.get("text", "")
                torch.cuda.synchronize()
                wall = time.perf_counter() - t0
                text, clean = strip_prompt_echo(text, prompt, tok,
                                                budget_tokens=gl)
                rec = {"text": text, "wall_s": wall, "prompt_echo_clean": clean,
                       "peak_decode_gb": torch.cuda.max_memory_allocated() / 1e9}
                try:
                    rec.update(dkv_kv_bytes(w.manager, it["length"], sid))
                except Exception as e:                           # noqa: BLE001
                    rec["kv_accounting_error"] = f"{type(e).__name__}: {e}"
                try:
                    w.clear_session(sid)
                except Exception:                                # noqa: BLE001
                    pass
            else:
                ids = tok(prompt, return_tensors="pt").input_ids[0].tolist()
                rec = KB.run_baseline(model, tok, ids, args.arm, "cuda", gl,
                                      stop_ids, args.chunk, bparams)
        except Exception as e:                                   # noqa: BLE001
            print(f"  [{n}/{len(work)}] {key}: ERROR {type(e).__name__}: {str(e)[:150]}")
            store.append(key, task=it["task"], length=it["length"], idx=it["idx"],
                         outputs=it["outputs"], error=f"{type(e).__name__}: {e}")
            continue

        fields = {"task": it["task"], "length": it["length"], "idx": it["idx"],
                  "outputs": it["outputs"], "inductor_fused": MSVC_OK}
        fields.update(rec)
        store.append(key, **fields)
        el = time.time() - t_start
        print(f"  [{n}/{len(work)}] {key} -> {repr(rec.get('text','')[:50])} "
              f"({el/n:.1f}s/item, ~{(len(work)-n)*el/n/60:.0f} min left)", flush=True)

    store.close()
    print()
    score_files([out])


if __name__ == "__main__":
    main()
