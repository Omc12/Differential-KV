import glob
import json
import os
import sys
import time
from collections import defaultdict
from typing import Any, Dict, List

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
ACTIVE = os.path.join(REPO, "ACTIVE_RUNTIME")
OFFICIAL = os.path.join(HERE, "ruler_official")

sys.path.insert(0, HERE)
from checkpoint import ResumableJSONL                            # noqa: E402
from code_fingerprint import decode_fingerprint          # noqa: E402

# task name -> generator family, which is what selects the official metric.
TASK_FAMILY = {
    "niah_single_1": "niah", "niah_single_2": "niah", "niah_single_3": "niah",
    "niah_multikey_1": "niah", "niah_multikey_2": "niah", "niah_multikey_3": "niah",
    "niah_multivalue": "niah", "niah_multiquery": "niah",
    "vt": "variable_tracking",
    "cwe": "common_words_extraction",
    "fwe": "freq_words_extraction",
    "qa_1": "qa", "qa_2": "qa",
}

RULER_13 = list(TASK_FAMILY)

# See run_longbench_cuda.MSVC_OK: per-record, not per-config, because quality is
# unaffected by the fused/unfused split but latency is.
MSVC_OK = False


def official_metric_fns():
    sys.path.insert(0, os.path.join(OFFICIAL, "eval", "synthetic"))
    import constants as C                                        # noqa: N813
    return {k: v["metric_fn"] for k, v in C.TASKS.items()}


def official_gen_tokens():
    sys.path.insert(0, os.path.join(OFFICIAL, "data", "synthetic"))
    import importlib.util
    spec = importlib.util.spec_from_file_location(
        "_ruler_gen_constants",
        os.path.join(OFFICIAL, "data", "synthetic", "constants.py"))
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return {k: v["tokens_to_generate"] for k, v in m.TASKS.items()}


def load_generated(data_dir: str) -> List[Dict[str, Any]]:
    """Every (length, task) that was generated under data_dir."""
    items = []
    for lend in sorted(os.listdir(data_dir), key=lambda x: int(x) if x.isdigit() else 0):
        lpath = os.path.join(data_dir, lend)
        if not (lend.isdigit() and os.path.isdir(lpath)):
            continue
        for task in sorted(os.listdir(lpath)):
            f = os.path.join(lpath, task, "validation.jsonl")
            if not os.path.exists(f):
                continue
            with open(f, encoding="utf-8") as fh:
                for i, line in enumerate(fh):
                    line = line.strip()
                    if not line:
                        continue
                    r = json.loads(line)
                    items.append({"length": int(lend), "task": task, "idx": i,
                                  "input": r["input"], "outputs": r["outputs"],
                                  "answer_prefix": r.get("answer_prefix", "")})
    return items


