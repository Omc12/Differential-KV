#!/usr/bin/env python3
"""RULER on CUDA, from NVIDIA's own generators and scorers, with checkpoints.

WHAT MAKES THIS THE REAL THING
------------------------------
The data is produced by RULER's own task generators (vendored unmodified under
benchmarks/ruler_official/, generated by benchmarks/generate_ruler_data.sh), so
the prompts, the haystacks, the needle placement and the answer prefixes are
the authors'. Scoring calls their `string_match_all` / `string_match_part`
directly rather than reimplementing string matching. RULER is legitimately a
synthetic GENERATOR -- "synthetic" was never the problem; a homemade
approximation of it was, because an approximation's numbers cannot be compared
against published RULER tables.

Per-task generation budgets come from RULER's constants.py (128 tokens for the
NIAH family, 30 for variable tracking, 120 for common-word extraction, 50 for
frequent-word extraction, 32 for QA), not from a number chosen here.

CONTEXT LENGTHS ARE THE ONES THE CARD CAN ACTUALLY HOLD. Whatever was
generated is what runs; the generator was pointed only at lengths each model's
measured ladder cleared without spilling into host memory. A spilled run's
quality is still real but its latency is PCIe bandwidth, and the two must not
share a table.

USAGE
    python benchmarks/run_ruler_cuda.py --model ibm-granite/granite-4.2-8b \
        --data paper/results/ruler_data/granite-4.2-8b \
        --arm dkv --preset mid --quant nf4

    python benchmarks/run_ruler_cuda.py --score "paper/results/ruler/*.jsonl"
"""

