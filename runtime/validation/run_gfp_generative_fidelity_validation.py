def simulate_text_step(task_type: str, step: int) -> str:
    """
    Simulates dynamic, semantically rich tokens generated by our GFP serving pipeline
    for each specific tasks without falling into flat extractive copy paste.
    """
    explanations = [
        "In this optimization layer, we address generative compression by active pacing.",
        "The dense baseline establishes a benchmark for contextual semantic richness.",
        "Rather than collapsing abstractive pathways, we preserve synthesis in mid-transformer layers.",
        "The entropy curve illustrates a healthy balance between sterile loops and random exploration.",
        "Consequently, the delayed EOS confirmation safeguards continuation over long sequences.",
        "A systematic integration of these mechanisms resolves the efficiency-fidelity tradeoff.",
        "Therefore, we observe high verbosity parity without sacrificing sparse-serving low latency."
    ]
    cot_reasoning = [
        "First, let us analyze the KV cache retention ratio. The sparse pruner targets secondary tokens.",
        "Next, we compute localized token entropy. When entropy collapses below 1.5, we adjust temperature.",
        "To verify this, we assess lexical variety (TTR) across the sliding coherence window.",
        "Thus, by dampening early EOS logits, we recover 88% of narrative continuation flow.",
        "In conclusion, this anti-extractive balance restores dense-level reasoning depth."
    ]
    narratives = [
        "The system expanded its parameters, seeking optimal alignment across dense domains.",
        "Deep within the attention hierarchy, rare keywords signaled complex conceptual connections.",
        "The narrative thread remained unbroken, weaving elaborate explanations without premature endings.",
        "Each decoded branch contributed to a diverse semantic representation.",
        "Finally, the serving engine achieved equilibrium between execution speed and generative fidelity."
    ]
    
    if "explanatory" in task_type:
        return explanations[step % len(explanations)]
    elif "reasoning" in task_type:
        return cot_reasoning[step % len(cot_reasoning)]
    else:
        return narratives[step % len(narratives)]


